export const LANGS = ['en', 'fr', 'ar'];
export const LANG_NAMES = { en: 'English', fr: 'Français', ar: 'العربية' };

const LANG_KEY = 'fq:settings';

export function detectLang() {
  try {
    const raw = localStorage.getItem(LANG_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (LANGS.includes(parsed.lang)) return parsed.lang;
    }
    const nav = (navigator.language || 'en').toLowerCase();
    if (nav.startsWith('ar')) return 'ar';
    if (nav.startsWith('fr')) return 'fr';
  } catch {
    /* fall through */
  }
  return 'en';
}

export function persistLang(lang) {
  try {
    const raw = localStorage.getItem(LANG_KEY);
    const cur = raw ? JSON.parse(raw) : {};
    localStorage.setItem(LANG_KEY, JSON.stringify({ ...cur, lang }));
  } catch {
    /* ignore */
  }
}

