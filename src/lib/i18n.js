const DIC = { fr: FR, ar: AR };

export function t(lang, key, vars = {}) {
  let s = (DIC[lang] && DIC[lang][key]) || key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.split(`{${k}}`).join(String(v ?? ''));
  }
  return s;
}